-- 데이터베이스 생성 (이름은 자유. 예: haksa)
CREATE DATABASE IF NOT EXISTS haksa DEFAULT CHARACTER SET utf8mb4;
USE haksa;

-- 재실행을 위해 자식 테이블부터 역순으로 제거 (FK 때문에 순서 중요)
DROP TABLE IF EXISTS TB_GRADE;
DROP TABLE IF EXISTS TB_CLASS_PROFESSOR;
DROP TABLE IF EXISTS TB_CLASS;
DROP TABLE IF EXISTS TB_STUDENT;
DROP TABLE IF EXISTS TB_PROFESSOR;
DROP TABLE IF EXISTS TB_DEPARTMENT;


-- =====================================================================
--  1. 테이블 생성 (모든 제약조건 포함: PK / FK / NOT NULL / DEFAULT / CHECK)
-- =====================================================================

-- 1-1. 학과
CREATE TABLE TB_DEPARTMENT (
    DEPARTMENT_NO    VARCHAR(10)   NOT NULL,
    DEPARTMENT_NAME  VARCHAR(20)   NOT NULL,
    CATEGORY         VARCHAR(20)   NULL,
    OPEN_YN          CHAR(1)       NULL DEFAULT 'Y',
    CAPACITY         INT           NULL,
    CONSTRAINT PK_DEPARTMENT       PRIMARY KEY (DEPARTMENT_NO),
    CONSTRAINT CK_DEPARTMENT_OPEN  CHECK (OPEN_YN IN ('Y', 'N')),
    CONSTRAINT CK_DEPARTMENT_CAP   CHECK (CAPACITY >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1-2. 교수 (DEPARTMENT_NO 는 학과 참조, 총장은 소속 학과가 없어 NULL 허용)
CREATE TABLE TB_PROFESSOR (
    PROFESSOR_NO       VARCHAR(10)  NOT NULL,
    PROFESSOR_NAME     VARCHAR(30)  NOT NULL,
    PROFESSOR_SSN      VARCHAR(14)  NULL,
    PROFESSOR_ADDRESS  VARCHAR(100) NULL,
    DEPARTMENT_NO      VARCHAR(10)  NULL,
    CONSTRAINT PK_PROFESSOR PRIMARY KEY (PROFESSOR_NO),
    CONSTRAINT FK_PROFESSOR_DEPARTMENT
        FOREIGN KEY (DEPARTMENT_NO) REFERENCES TB_DEPARTMENT (DEPARTMENT_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1-3. 학생 (학과 참조 필수, 지도교수는 없을 수 있어 NULL 허용)
CREATE TABLE TB_STUDENT (
    STUDENT_NO          VARCHAR(10)  NOT NULL,
    DEPARTMENT_NO       VARCHAR(10)  NOT NULL,
    STUDENT_NAME        VARCHAR(30)  NOT NULL,
    STUDENT_SSN         VARCHAR(14)  NULL,
    STUDENT_ADDRESS     VARCHAR(100) NULL,
    ENTRANCE_DATE       DATE         NULL,
    ABSENCE_YN          CHAR(1)      NULL DEFAULT 'N',
    COACH_PROFESSOR_NO  VARCHAR(10)  NULL,
    CONSTRAINT PK_STUDENT PRIMARY KEY (STUDENT_NO),
    CONSTRAINT FK_STUDENT_DEPARTMENT
        FOREIGN KEY (DEPARTMENT_NO)      REFERENCES TB_DEPARTMENT (DEPARTMENT_NO),
    CONSTRAINT FK_STUDENT_PROFESSOR
        FOREIGN KEY (COACH_PROFESSOR_NO) REFERENCES TB_PROFESSOR (PROFESSOR_NO),
    CONSTRAINT CK_STUDENT_ABSENCE CHECK (ABSENCE_YN IN ('Y', 'N'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1-4. 과목 (학과 참조 필수, 선수과목은 같은 테이블의 CLASS_NO 를 자기참조)
CREATE TABLE TB_CLASS (
    CLASS_NO               VARCHAR(10) NOT NULL,
    DEPARTMENT_NO          VARCHAR(10) NOT NULL,
    PREATTENDING_CLASS_NO  VARCHAR(10) NULL,
    CLASS_NAME             VARCHAR(30) NOT NULL,
    CLASS_TYPE             VARCHAR(10) NULL,
    CONSTRAINT PK_CLASS PRIMARY KEY (CLASS_NO),
    CONSTRAINT FK_CLASS_DEPARTMENT
        FOREIGN KEY (DEPARTMENT_NO)         REFERENCES TB_DEPARTMENT (DEPARTMENT_NO),
    CONSTRAINT FK_CLASS_PREATTEND
        FOREIGN KEY (PREATTENDING_CLASS_NO) REFERENCES TB_CLASS (CLASS_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1-5. 과목 교수 (과목-교수 다대다, 두 컬럼이 함께 PK)
CREATE TABLE TB_CLASS_PROFESSOR (
    CLASS_NO      VARCHAR(10) NOT NULL,
    PROFESSOR_NO  VARCHAR(10) NOT NULL,
    CONSTRAINT PK_CLASS_PROFESSOR PRIMARY KEY (CLASS_NO, PROFESSOR_NO),
    CONSTRAINT FK_CLASSPROF_CLASS
        FOREIGN KEY (CLASS_NO)     REFERENCES TB_CLASS (CLASS_NO),
    CONSTRAINT FK_CLASSPROF_PROFESSOR
        FOREIGN KEY (PROFESSOR_NO) REFERENCES TB_PROFESSOR (PROFESSOR_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 1-6. 성적 (학기+과목+학생 조합이 PK, POINT 는 0.00 ~ 4.50)
CREATE TABLE TB_GRADE (
    TERM_NO     VARCHAR(10)   NOT NULL,
    CLASS_NO    VARCHAR(10)   NOT NULL,
    STUDENT_NO  VARCHAR(10)   NOT NULL,
    POINT       DECIMAL(3, 2) NULL,
    CONSTRAINT PK_GRADE PRIMARY KEY (TERM_NO, CLASS_NO, STUDENT_NO),
    CONSTRAINT FK_GRADE_CLASS
        FOREIGN KEY (CLASS_NO)   REFERENCES TB_CLASS (CLASS_NO),
    CONSTRAINT FK_GRADE_STUDENT
        FOREIGN KEY (STUDENT_NO) REFERENCES TB_STUDENT (STUDENT_NO),
    CONSTRAINT CK_GRADE_POINT CHECK (POINT >= 0 AND POINT <= 4.5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


